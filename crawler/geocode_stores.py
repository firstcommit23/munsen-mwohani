def run():
    init_db()
    conn = get_connection()
    cur = conn.cursor()

    stores = cur.execute("SELECT id, name FROM stores").fetchall()
    updated = 0
    missing = []

    for store in stores:
        store_id = store["id"]
        name = store["name"]
        coords = COORDS.get(name)
        if coords:
            cur.execute("UPDATE stores SET lat=?, lng=? WHERE id=?", (*coords, store_id))
            print(f"  ✓ {name}: {coords}")
            updated += 1
        else:
            missing.append(name)

    conn.commit()
    conn.close()

    print(f"\n완료: {updated}개 좌표 입력")
    if missing:
        print(f"누락 {len(missing)}개:")
        for m in missing:
            print(f"  - {m}")


if __name__ == "__main__":
    run()
